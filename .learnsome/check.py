SEARCH_PATH = os.pathsep.join([os.path.join(ROOT, 'node_modules', '.bin'), os.environ.get('PATH', '')])


def which(tool):
    return shutil.which(tool, path=SEARCH_PATH)


def missing_tools(lab):
    return [t for t in lab.get('requires', []) if not which(t)]


_go_cache = None


def go_env():
    global _go_cache
    if _go_cache is None:
        _go_cache = os.environ.get('GOCACHE', '')
        if not _go_cache:
            try:
                out = subprocess.run(['go', 'env', 'GOCACHE'], capture_output=True, text=True, env={**os.environ, 'PATH': SEARCH_PATH})
                _go_cache = out.stdout.strip() if out.returncode == 0 else ''
            except OSError:
                _go_cache = ''
    env = {'GOTOOLCHAIN': 'local', 'GOPROXY': 'off', 'GOSUMDB': 'off', 'CGO_ENABLED': '0', 'GOFLAGS': '-buildvcs=false'}
    if _go_cache:
        env['GOCACHE'] = _go_cache
    return env


def kube_schemas():
    """The Kubernetes schemas the site validates against: fetched once, checked against their SHA-256 sums."""
    k8s = COURSE['kubeconform']
    d = os.environ.get('LEARNSOME_K8S_SCHEMAS') or os.path.join(ROOT, '.learnsome', 'cache', 'k8s-schemas')
    os.makedirs(d, exist_ok=True)
    for digest, name in k8s['schemas']:
        path = os.path.join(d, name)

        def ok():
            if not os.path.isfile(path):
                return False
            with open(path, 'rb') as f:
                return hashlib.sha256(f.read()).hexdigest() == digest

        if ok():
            continue
        with urllib.request.urlopen(f"{k8s['url']}/{name}", timeout=30) as resp, open(path, 'wb') as f:
            f.write(resp.read())
        if not ok():
            raise RuntimeError(f'could not fetch the Kubernetes schema {name}')
    return d


TERRAFORM = 'if ls ./*.tf >/dev/null 2>&1; then terraform init -input=false -no-color >/dev/null 2>&1; fi; exec sh "$1"'
