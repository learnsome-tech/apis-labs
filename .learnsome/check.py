def list_files(d):
    out = []
    for root, _dirs, names in os.walk(d):
        for n in names:
            out.append(os.path.relpath(os.path.join(root, n), d).replace(os.sep, '/'))
    return out


def lint_structure(problems):
    entries = manifest()
    known = {e['dir'] for e in entries}
    lesson_dirs = sorted({os.path.dirname(e['dir']) for e in entries})
    for lesson_dir in lesson_dirs:
        if not os.path.isfile(os.path.join(ROOT, lesson_dir, 'README.md')):
            problems.append(f'{lesson_dir}: no README.md')
        for name in sorted(os.listdir(os.path.join(ROOT, lesson_dir))):
            rel = f'{lesson_dir}/{name}'
            if name != 'README.md' and rel not in known:
                problems.append(f'{rel}: not a lab of this course')
            elif rel in known and not os.path.isdir(os.path.join(ROOT, rel)):
                problems.append(f'{rel}: not a directory')
    for name in sorted(os.listdir(os.path.join(ROOT, 'labs'))):
        if f'labs/{name}' not in lesson_dirs:
            problems.append(f'labs/{name}: not a lesson of this course')
    for entry in entries:
        d = os.path.join(ROOT, entry['dir'])
        where = entry['dir']
        if not os.path.isfile(os.path.join(d, 'README.md')):
            problems.append(f'{where}: no README.md')
        try:
            lab = load_lab(entry)
        except FileNotFoundError:
            problems.append(f'{where}/check.json: missing')
            continue
        except ValueError as err:
            problems.append(f'{where}/check.json: {err}')
            continue
        if lab.get('lab') != entry['lab']:
            problems.append(f"{where}/check.json: lab is {lab.get('lab')}, expected {entry['lab']}")
        if lab.get('mode') not in MODES:
            problems.append(f"{where}/check.json: unknown mode {lab.get('mode')}")
        if lab.get('mode') != 'read-along' and not lab.get('runner'):
            problems.append(f'{where}/check.json: no runner')
        if lab.get('mode') in ('read-along', 'run') and not lab.get('note'):
            problems.append(f'{where}/check.json: no note')
        for name in sorted(os.listdir(d)):
            if name not in LAB_FILES:
                problems.append(f'{where}/{name}: not part of the lab')
        if lab.get('mode') == 'graded':
            if not lab.get('expected') or not os.path.isfile(os.path.join(d, lab['expected'])):
                problems.append(f'{where}: graded but has no expected output')
            if not lab.get('grading'):
                problems.append(f'{where}/check.json: graded without a grading rule')
        elif os.path.exists(os.path.join(d, 'expected.txt')):
            problems.append(f'{where}/expected.txt: only graded labs have expected output')
        files = set(lab.get('files', []))
        if lab.get('main') not in files:
            problems.append(f"{where}/check.json: main file {lab.get('main')} is not listed")
        for name in sorted(files):
            if not os.path.isfile(os.path.join(d, 'starter', name)):
                problems.append(f'{where}/starter/{name}: missing')
        starter = os.path.join(d, 'starter')
        for name in sorted(list_files(starter) if os.path.isdir(starter) else []):
            if name not in files:
                problems.append(f'{where}/starter/{name}: not listed in check.json')
        if lab.get('stdin') and lab['stdin'] not in files:
            problems.append(f"{where}/check.json: stdin file {lab['stdin']} is not a starter file")
        for s in lab.get('shared', []):
            if not os.path.isfile(os.path.join(ROOT, s['from'])):
                problems.append(f"{where}: shared file {s['from']} missing")


LANGUAGE_FILES = {
    'python': ('.py',), 'pytest': ('.py',), 'bash': ('.sh',), 'recorded': ('.sh',), 'go': ('.go',), 'java': ('.java',),
    'node': ('.js', '.mjs', '.cjs'),
}


def _tail(text, n=4):
    return '\n'.join(text.strip().split('\n')[-n:])


def lint_syntax(problems, missing):
    for entry in manifest():
        lab = load_lab(entry)
        if lab['mode'] == 'read-along' or lab.get('syntax') is False:
            continue
        if lab['runner'] == 'csharp':
            if not which('dotnet'):
                missing.add('dotnet')
                continue
            base = tempfile.mkdtemp(prefix='learnsome-dotnet-')
            home = os.path.join(base, 'home')
            try:
                for name in lab['files']:
                    target = os.path.join(home, name)
                    os.makedirs(os.path.dirname(target), exist_ok=True)
                    shutil.copyfile(os.path.join(lab['dir'], 'starter', name), target)
                ok, out = build_csharp(home, {**os.environ, 'PATH': SEARCH_PATH, **DOTNET_ENV,
                                              'DOTNET_CLI_HOME': base, 'NUGET_PACKAGES': os.path.join(base, 'nuget')})
            finally:
                shutil.rmtree(base, ignore_errors=True)
            if not ok:
                problems.append(f"{lab['relDir']}/starter: does not compile\n" + '\n'.join(out.strip().split('\n')[:6]))
            continue
        exts = LANGUAGE_FILES.get(lab['runner'], ())
        # A recorded shell session is bash, whatever its extension.
        files = [f for f in lab['files'] if (f == lab['main'] and lab['runner'] == 'bash') or os.path.splitext(f)[1] in exts]
        java_files = []
        for name in files:
            path = os.path.join(lab['dir'], 'starter', name)
            where = f"{lab['relDir']}/starter/{name}"
            ext = os.path.splitext(name)[1]
            if ext == '.java':
                java_files.append(path)
                continue
            if lab['runner'] in ('python', 'pytest') and ext == '.py':
                import ast
                try:
                    with open(path, 'rb') as f:
                        ast.parse(f.read(), path)
                except SyntaxError as err:
                    problems.append(f'{where}: does not parse\n{err}')
                continue
            if lab['runner'] in ('bash', 'recorded') or ext == '.sh':
                tool, args = 'bash', ['-n', path]
            elif ext == '.go':
                tool, args = 'gofmt', ['-e', '-l', path]
            elif ext in ('.js', '.mjs', '.cjs'):
                tool, args = 'node', ['--check', path]
            else:
                continue
            if not which(tool):
                missing.add(tool)
                continue
            res = subprocess.run([tool, *args], capture_output=True, text=True, env={**os.environ, 'PATH': SEARCH_PATH})
            if res.returncode != 0:
                problems.append(f'{where}: does not parse\n{_tail(res.stderr or res.stdout)}')
        if java_files:
            if not which('javac'):
                missing.add('javac')
                continue
            # `java File.java` compiles that one file, whatever its public type is called; javac wants the file
            # named after it, so the check compiles a copy under that name.
            with open(os.path.join(lab['dir'], 'starter', lab['main']), encoding='utf-8') as f:
                source = f.read()
            m = PUBLIC_TYPE.search(source)
            out = tempfile.mkdtemp(prefix='learnsome-javac-')
            copy = os.path.join(out, f'{m.group(1) if m else os.path.splitext(lab["main"])[0]}.java')
            with open(copy, 'w', encoding='utf-8') as f:
                f.write(source)
            res = subprocess.run(['javac', '-proc:none', '-nowarn', '-d', out, copy], capture_output=True, text=True)
            shutil.rmtree(out, ignore_errors=True)
            if res.returncode != 0:
                problems.append(f"{lab['relDir']}/starter/{lab['main']}: does not compile\n" + '\n'.join(res.stderr.strip().split('\n')[:6]))


PUBLIC_TYPE = re.compile(r'^\s*public\s+(?:(?:abstract|final|sealed|non-sealed|static|strictfp)\s+)*(?:class|record|interface|enum|@interface)\s+(\w+)', re.M)


def lint(strict):
    problems = []
    missing = set()
    lint_structure(problems)
    lint_syntax(problems, missing)
    # The checker labs: the starter must pass the site's checker (hadolint, actionlint, kubeconform...).
    checked = 0
    for entry in manifest():
        lab = load_lab(entry)
        if lab['mode'] != 'checker':
            continue
        tools = missing_tools(lab)
        if tools:
            missing.update(tools)
            continue
        result = execute(lab)
        checked += 1
        if result['exitCode'] != 0 or result['timedOut']:
            out = '\n'.join((result['stdout'] + result['stderr']).strip().split('\n')[:6])
            problems.append(f"{lab['relDir']}: {lab['command']} failed (exit {result['exitCode']})\n{out}")
    for p in problems:
        print(f"{STATUS['FAIL']}  {p}")
    if missing:
        print(f"{STATUS['FAIL'] if strict else STATUS['SKIP']}  not checked, missing on PATH: {', '.join(sorted(missing))}")
    summary = f'{len(problems)} problems' if problems else 'structure and syntax OK'
    print(f"{len(manifest())} labs: {summary}{f', {checked} checker labs run' if checked else ''}")
    return 1 if problems or (strict and missing) else 0


