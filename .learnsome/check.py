# ---------- labs ----------


def read_json(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def manifest():
    return read_json(os.path.join(ROOT, '.learnsome', 'labs.json'))


def load_lab(entry):
    d = os.path.join(ROOT, entry['dir'])
    lab = read_json(os.path.join(d, 'check.json'))
    lab['dir'] = d
    lab['relDir'] = entry['dir']
    return lab


def select(names):
    """Labs named on the command line: a lab id (m01l01-02), a lesson id (m01l01) or a path in a lab."""
    entries = manifest()
    picked = {}
    for name in names:
        rel = os.path.relpath(os.path.abspath(name), ROOT).replace(os.sep, '/')
        found = [e for e in entries if e['lab'] == name or e['lesson'] == name or rel == e['dir'] or rel.startswith(e['dir'] + '/')]
        if not found:
            print(f'check: no lab called {name} (./check --list shows them)', file=sys.stderr)
            sys.exit(2)
        for e in found:
            picked.setdefault(e['dir'], e)
    return list(picked.values())


