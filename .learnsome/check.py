"""The lab checker of a LearnSome.tech labs repository (run it through ./check).

It runs a lab the way the site's lab sandbox does (workers/labs/run_lab.py on the platform): the starter
files copied into a scratch directory that is the program's working directory and HOME, TMPDIR in a
scratch directory of its own, LANG=C.UTF-8 and TZ=UTC, input.txt on stdin, a 10 second limit and 256 KiB
of output per stream. The output is graded with the site's own comparison rules (grading.py).
Generated by the LearnSome.tech platform (scripts/labs-repos); do not edit here.
"""
