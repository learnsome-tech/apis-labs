"""Output grading of LearnSome.tech labs: a line-for-line port of the platform grader
(workers/labs/src/grading.js), so a pass here is a pass on the site. JavaScript's regular expression
semantics are kept where they differ from Python's: `\\s` and trimming use JavaScript's whitespace set,
`\\d` and `\\w` are ASCII, `.` stops at every line terminator, and `$` is the end of the text.

Generated by the LearnSome.tech platform (scripts/labs-repos); do not edit here.
"""
import math
import re

# JavaScript's WhiteSpace and LineTerminator characters: what `\s` matches and String#trim removes.
JS_SPACE = '\t\n\x0b\x0c\r \xa0\u1680\u2000\u2001\u2002\u2003\u2004\u2005\u2006\u2007\u2008\u2009\u200a\u2028\u2029\u202f\u205f\u3000\ufeff'
_S = '[' + re.escape(JS_SPACE) + ']'
_NS = '[^' + re.escape(JS_SPACE) + ']'
_DOT = '[^\n\r\u2028\u2029]'
MAX_DIFF = 200


def _trim_end(s):
    return s.rstrip(JS_SPACE)


def _trim(s):
    return s.strip(JS_SPACE)


def _newlines(text):
    return re.sub(r'\r\n?', '\n', text)


def normalize_lines(text):
    """Contract comparison: per-line trailing whitespace trimmed, trailing blank lines ignored."""
    joined = '\n'.join(_trim_end(line) for line in _newlines(text).split('\n'))
    return joined.rstrip('\n').split('\n')


_TRACEBACK = re.compile(r'^Traceback \(most recent call last\):' + _S + r'*\Z')
_FILE_LINE = re.compile('^' + _S + r'+File "' + _DOT + r'*", line [0-9]+')
_CARET = re.compile('^' + _S + r'*[\^~]+' + _S + r'*\Z')
_SOURCE = re.compile('^' + _S + '{4}' + _NS)


def course_normalize(text):
    """Traceback scaffolding (File/source/caret lines) and blank lines set aside."""
    out = []
    for line in _newlines(text).split('\n'):
        if _TRACEBACK.search(line) or _FILE_LINE.search(line) or _CARET.search(line) or _SOURCE.search(line):
            continue
        line = _trim_end(line)
        if line != '':
            out.append(line)
    return '\n'.join(out)


def _diff(actual, expected):
    diff = []
    for i in range(max(len(actual), len(expected))):
        if len(diff) >= MAX_DIFF:
            break
        a = actual[i] if i < len(actual) else None
        e = expected[i] if i < len(expected) else None
        if a != e:
            diff.append({'line': i + 1, 'expected': e, 'actual': a})
    return diff


def line_diff(actual_text, expected_text):
    return _diff(normalize_lines(actual_text), normalize_lines(expected_text))


# sqlite3 builds differ in column alignment and float printing, so SQL result sets are compared cell by cell.
_SQL_ERROR = re.compile(r'^(?:Runtime error|Error|Parse error)(?: near line [0-9]+)?: (' + _DOT + r'*?)(?: \([0-9]+\))?\Z')


def _sql_error(line):
    line = _SQL_ERROR.sub(lambda m: 'ERROR: ' + m.group(1), line, count=1)
    return _trim(re.sub(_S + '+', ' ', line))


def _sql_cells(line):
    return [c for c in re.split(_S + '{2,}', _trim(line)) if c]


_DECIMAL = re.compile(r'[+-]?(?:[0-9]+\.?[0-9]*|\.[0-9]+)(?:[eE][+-]?[0-9]+)?\Z')
_RADIX = {'x': (16, '0123456789abcdefABCDEF'), 'o': (8, '01234567'), 'b': (2, '01')}


def js_number(text):
    """JavaScript's Number(text) for a string."""
    s = _trim(text)
    if s == '':
        return 0.0
    if _DECIMAL.match(s):
        return float(s)
    if s in ('Infinity', '+Infinity'):
        return math.inf
    if s == '-Infinity':
        return -math.inf
    if len(s) > 2 and s[0] == '0' and s[1].lower() in _RADIX:
        base, digits = _RADIX[s[1].lower()]
        if all(ch in digits for ch in s[2:]):
            return float(int(s[2:], base))
    return math.nan


def _sql_cell_equals(a, b):
    if a == b:
        return True
    x = js_number(a)
    y = js_number(b)
    return a != '' and b != '' and not math.isnan(x) and not math.isnan(y) and abs(x - y) < 1e-4


_RULE = re.compile(r'^[- ]+\Z')


def _sql_line_equals(exp, act):
    if exp == act:
        return True
    e = _sql_error(exp)
    if e.startswith('ERROR:') and e == _sql_error(act):
        return True
    if _RULE.match(exp) and _RULE.match(act):
        return True
    ec = _sql_cells(exp)
    ac = _sql_cells(act)
    return len(ec) > 0 and len(ec) == len(ac) and all(_sql_cell_equals(c, ac[i]) for i, c in enumerate(ec))


def _sql_same_output(expected_text, actual_text):
    def clean(t):
        return [line for line in (_trim_end(x) for x in _newlines(t).split('\n')) if _trim(line) != '']

    exp = clean(expected_text)
    act = clean(actual_text)
    return len(exp) == len(act) and all(_sql_line_equals(line, act[i]) for i, line in enumerate(exp))


ANSI = re.compile(r'\x1b\[[0-9;?]*[A-Za-z]')

_ANSIBLE_WARNING_START = re.compile('^' + _S + r'*\[(?:WARNING|DEPRECATION WARNING|NOTICE)\]')
_ANSIBLE_ROW = re.compile(r'^(?:PLAY|TASK|RUNNING HANDLER|HANDLER|ok:|changed:|failed:|fatal:|skipping:|ignoring:|included:|localhost|---|\+\+\+|@@)')
_ANSIBLE_ENVIRONMENTAL = [
    re.compile('^' + _S + r'*\[WARNING\]'),
    re.compile('^' + _S + r'*\[DEPRECATION WARNING\]'),
    re.compile(r'^You are using'),
    re.compile('^' + _S + r'*no action detected in task'),
    re.compile(r'Python interpreter'),
    re.compile('^' + _S + r'*See https://docs\.ansible\.com'),
]


def ansible_normalize(text):
    out = []
    in_warning = False
    for raw in _newlines(text).split('\n'):
        line = ANSI.sub('', raw)
        if _ANSIBLE_WARNING_START.search(line):
            in_warning = True
            continue
        if in_warning:
            if not _ANSIBLE_ROW.search(line):
                continue
            in_warning = False
        if any(r.search(line) for r in _ANSIBLE_ENVIRONMENTAL):
            continue
        collapsed = re.sub(r'\*{2,}', '***', line)
        collapsed = re.sub(r'={3,}', '===', collapsed)
        collapsed = _trim(re.sub(_S + '+', ' ', collapsed))
        if collapsed != '':
            out.append(collapsed)
    return out


