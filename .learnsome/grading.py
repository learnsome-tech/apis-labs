def _terraform_mask(line):
    for pattern, replacement in _TERRAFORM_MASKS:
        line = pattern.sub(lambda _m, r=replacement: r, line)
    return line


def terraform_normalize(text):
    out = []
    for raw in _newlines(text).split('\n'):
        line = _trim_end(ANSI.sub('', raw))
        if line != '' and not any(r.search(line) for r in _TERRAFORM_NOISE):
            out.append(_terraform_mask(line))
    return out



# dotnet-course scripts/output.ts: SDK restore, build and test-platform banners, Kestrel's start-up lines and
# stack-trace frames dropped; times, paths, guids and timestamps masked; blank lines ignored.
def _dn(pattern):
    """A DOTNET_NOISE pattern in JavaScript notation: \\s, \\S, \\d and . as JavaScript means them."""
    out = pattern.replace(r'\S', '\x00NS\x00').replace(r'\s', '\x00S\x00').replace(r'\d', '[0-9]').replace('.*', '\x00DOT\x00*')
    out = out.replace('\x00NS\x00', _NS).replace('\x00S\x00', _S).replace('\x00DOT\x00', _DOT)
    if out.endswith('$'):
        out = out[:-1] + r'\Z'
    return re.compile(out, re.ASCII)


